import streamlit as st
import plotly.graph_objects as go
from model import defaults, simulate, SOLVENTS
st.set_page_config(page_title='Dual ANFD First-Principles Model',layout='wide')
st.title('Dual ANFD Heat & Mass-Transfer Model')
st.caption('Rosenmund fixed vertical cake | OMCA tilt-dependent bed | mechanistic screening model')
kind=st.sidebar.selectbox('Equipment',['Rosenmund','OMCA'])
eq,prod,rec=defaults(kind)
st.sidebar.header('Geometry and operation')
eq.filter_area_m2=st.sidebar.number_input('Filter area (m²)',0.001,2.0,eq.filter_area_m2,0.001)
eq.vessel_diameter_m=st.sidebar.number_input('Internal diameter (m)',0.05,3.0,eq.vessel_diameter_m,0.005)
eq.vessel_length_m=st.sidebar.number_input('Usable length/height (m)',0.05,5.0,eq.vessel_length_m,0.01)
eq.headspace_m3=st.sidebar.number_input('Headspace (m³)',0.001,5.0,eq.headspace_m3,0.001)
eq.rpm=st.sidebar.slider('Agitator RPM',0,120,int(eq.rpm))
eq.agitation_duty=st.sidebar.slider('Agitation duty fraction',0.0,1.0,float(eq.agitation_duty),0.05)
if kind=='OMCA': eq.tilt_deg=st.sidebar.slider('Tilt angle (°)',-90,90,int(eq.tilt_deg))
st.sidebar.header('Heat transfer')
eq.base_UA_WK=st.sidebar.number_input('Base UA (W/K)',0.0,1000.0,eq.base_UA_WK,0.5)
eq.wall_UA_WK=st.sidebar.number_input('Wall UA (W/K)',0.0,1000.0,eq.wall_UA_WK,0.5)
eq.agitator_UA_WK=st.sidebar.number_input('Agitator UA (W/K)',0.0,1000.0,eq.agitator_UA_WK,0.5)
st.sidebar.header('Product')
prod.dry_mass_kg=st.sidebar.number_input('Dry solids (kg)',0.01,1000.0,prod.dry_mass_kg,0.1)
prod.wet_bulk_density_kgm3=st.sidebar.number_input('Wet bulk density (kg/m³)',50.0,2000.0,prod.wet_bulk_density_kgm3,10.0)
prod.dry_Tg_C=st.sidebar.number_input('Dry PLGA Tg (°C)',0.0,100.0,prod.dry_Tg_C,1.0)
for s in SOLVENTS: prod.initial_solvent_kg[s]=st.sidebar.number_input(f'Initial {s} (kg)',0.0,100.0,prod.initial_solvent_kg[s],0.005)
st.sidebar.header('Recipe')
rec.total_h=st.sidebar.number_input('Simulation duration (h)',1.0,200.0,rec.total_h,1.0)
rec.pressure_mbar=st.sidebar.number_input('Absolute pressure (mbar)',1.0,1000.0,rec.pressure_mbar,5.0)
eq.condenser_temp_C=st.sidebar.number_input('Condenser temperature (°C)',-80.0,30.0,eq.condenser_temp_C,1.0)
profile_text=st.sidebar.text_area('Jacket profile: hour,temp per line','\n'.join(f'{a},{b}' for a,b in rec.jacket_profile),height=140)
try: rec.jacket_profile=[tuple(map(float,x.split(','))) for x in profile_text.splitlines() if x.strip()]
except: st.sidebar.error('Use hour,temp format')
with st.spinner('Solving balances...'):
    df,meta=simulate(eq,prod,rec)
cols=st.columns(4)
cols[0].metric('Cake depth',f"{meta['geometry']['cake_depth_m']*1000:.1f} mm")
cols[1].metric('Minimum Tg margin',f"{df.Tg_margin_C.min():.1f} °C")
cols[2].metric('Final DCM',f"{df.DCM_ppm.iloc[-1]:,.0f} ppm")
cols[3].metric('Final ethanol',f"{df.Ethanol_ppm.iloc[-1]:,.0f} ppm")
fig=go.Figure()
for y,n in [('jacket_C','Jacket'),('product_C','Product'),('Tg_C','Dynamic Tg')]: fig.add_scatter(x=df.time_h,y=df[y],name=n)
fig.update_layout(title='Temperature and Tg',xaxis_title='Time (h)',yaxis_title='Temperature (°C)',hovermode='x unified')
st.plotly_chart(fig,use_container_width=True)
fig2=go.Figure()
for s in SOLVENTS: fig2.add_scatter(x=df.time_h,y=df[f'{s}_ppm'],name=s)
fig2.update_layout(title='Residual solvents',xaxis_title='Time (h)',yaxis_title='ppm on dry solids',yaxis_type='log',hovermode='x unified')
st.plotly_chart(fig2,use_container_width=True)
c1,c2=st.columns(2)
with c1:
 f=go.Figure(); f.add_scatter(x=df.time_h,y=df.heat_W,name='Heat supplied'); f.add_scatter(x=df.time_h,y=df.latent_W,name='Evaporation duty'); f.update_layout(title='Energy balance',xaxis_title='Time (h)',yaxis_title='W'); st.plotly_chart(f,use_container_width=True)
with c2:
 f=go.Figure();
 for s in SOLVENTS: f.add_scatter(x=df.time_h,y=df[f'{s}_condensed_g'],name=s)
 f.update_layout(title='Cumulative condensed solvent',xaxis_title='Time (h)',yaxis_title='g'); st.plotly_chart(f,use_container_width=True)
st.subheader('Data and model warnings')
w=[]
if df.Tg_margin_C.min()<5: w.append('Tg safety margin falls below 5 °C.')
if kind=='OMCA': w.append('OMCA dimensions are editable placeholders until the approved dimensional schedule is entered.')
if rec.pressure_mbar!=80: w.append('Pressure is recorded but the current screening kernel uses effective pumping speed; calibrate pump/line conductance before validation.')
for x in w: st.warning(x)
st.dataframe(df.iloc[::max(1,len(df)//500)],use_container_width=True)
st.download_button('Download simulation CSV',df.to_csv(index=False).encode(),'anfd_simulation.csv','text/csv')
